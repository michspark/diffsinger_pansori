#!/usr/bin/env python3
"""PreToolUse(Edit|Write|MultiEdit) -- keep upstream files untouched.

The whole fork rests on one rule, stated in pansori/README.md:

    upstream 파일은 한 줄도 고치지 않았다. 우리 코드는 pansori/,
    dictionaries/korean-coda.txt, configs/pansori/, configs/exp/ 에만 있다.
    rebase 를 계속 감당하려면 그 상태를 유지할 것.

Until now that rule was held by attention alone, and the cost of breaking it is
not paid at the moment of the edit -- it is paid at every future rebase onto
openvpi. This hook moves it from discipline to mechanism.

It also refuses writes into the artefact trees (checkpoints/, data/, ...), which
are gigabytes of generated output that no edit should ever land in.
"""

import sys
from pathlib import Path

sys.path.insert(0, str(Path(__file__).parent))

from _common import (  # noqa: E402
    ARTEFACT_DIRS, FORK_OWNED, FORK_OWNED_FILES, GENERATED_DIRS,
    deny, edited_paths, payload, project_dir, rel_path, run, under,
)

UPSTREAM_MESSAGE = """\
Refused: {rel} is an upstream (openvpi) file, and this fork does not modify upstream files.

    "upstream 파일은 한 줄도 고치지 않았다 ... rebase 를 계속 감당하려면 그 상태를 유지할 것."
    -- pansori/README.md

Fork code lives only in: pansori/, configs/pansori/, configs/exp/,
dictionaries/korean-coda.txt.

Add the behaviour from the outside instead. The three patterns already in use here:
  * subclass and select by config string -- pansori/variance_task.py, reached via
    `task_cls: pansori.variance_task.PansoriVarianceTask`
  * wrap the entry point -- pansori/train.py is scripts/train.py + wandb
  * patch at a seam -- pansori/train.py patches SummaryWriter because the logger is
    hard-wired at basics/base_task.py:427

If this edit genuinely cannot be done from outside, say so and ask before proceeding."""

ARTEFACT_MESSAGE = """\
Refused: {rel} is generated data, not source.

{top}/ holds binarized corpora, checkpoints or evaluation output -- gigabytes of it,
all gitignored. Regenerate it with the pipeline that owns it rather than editing it."""

GENERATED_MESSAGE = """\
Refused: {rel} is generated by pansori/make_configs.py -- edit the generator, not its output.

Per-run settings do not belong here at all. A run's conditions go in its own
configs/exp/*.yaml, which is hand-written and stays in git:

    base_config:
      - configs/pansori/acoustic.yaml
      - configs/pansori/data_pansori.yaml
    binary_data_dir: data/pansori/binary_acoustic
    max_updates: 50000

Regenerate the layer with: python pansori/make_configs.py [--data DIR --name NAME]"""


def main():
    data = payload()
    root = project_dir()

    for raw in edited_paths(data):
        rel = rel_path(raw, root)
        if rel is None:
            continue  # outside the repo -- not ours to police

        if under(rel, ARTEFACT_DIRS):
            top = next(d for d in ARTEFACT_DIRS if under(rel, (d,)))
            deny(ARTEFACT_MESSAGE.format(rel=rel, top=top))

        if under(rel, GENERATED_DIRS):
            deny(GENERATED_MESSAGE.format(rel=rel))

        if under(rel, FORK_OWNED) or rel in FORK_OWNED_FILES:
            continue

        deny(UPSTREAM_MESSAGE.format(rel=rel))


run(main)
