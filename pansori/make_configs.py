#!/usr/bin/env python3
"""Render the generated layers of configs/pansori/.

The old generator wrote one 191-line file per (corpus, kind). Of those lines 122
were the `datasets:` block, and the whisper/snapped pair differed in nothing but
a path -- so a second corpus cost a second 191-line copy, and a run's actual
conditions (max_updates, num_ckpt_keep) lived only in a `--hparams` string in
somebody's shell history.

So the config is split along the three axes that actually vary, and upstream's
own `base_config` chain puts them back together (utils/hparams.py:64-82 loads the
list in order, then lets the file's own keys win):

    configs/pansori/{acoustic,variance}.yaml   kind. Knows nothing about the corpus.
    configs/pansori/data_{name}.yaml           corpus. datasets + num_spk.
    configs/exp/*.yaml                         experiment. Hand-written, kept in git.

`binary_data_dir` is the one key that depends on both axes, so the experiment
file states it. That is not a workaround -- which binarized corpus a run reads is
the single most important fact about it, and it belongs where a reader looks.

    python pansori/make_configs.py                                   # data/pansori
    python pansori/make_configs.py --data data/pansori_snap --name snap
"""

import argparse
import csv
from pathlib import Path

# One held-out song per myeongchang, carried over from the MoonInTheRiver run so the
# test set stays directly comparable with the numbers in docs/PORTING.md.
# split_train_valid_set matches with startswith and item names are
# {uuid8}_{index}, so a bare uuid holds out a whole song.
HOLDOUT = {
    '조상현': '8b4d0824',   # Chunhyangga, 'and then the royal inspector'
    '정권진': 'a580300d',   # Simcheongga, Ppaengpa
    '이일주': 'c235c995',   # Simcheongga, Simcheong's farewell
    '박동진': 'e719dced',   # Sugungga
    '박초월': 'd7ec123c',   # Sugungga, the rabbit enters the dragon palace
    '김소희': 'd207244a',   # Chunhyangga, Yi Doryeong's farewell
}

# This corpus's mel envelope. openvpi's default spec_max:[0] does not suit pansori --
# the measured ceiling is +2.84, so after normalisation the diffusion target leaves
# [-1, 1]. pansori/compute_spec_stats.py generates it from the binarize output. The
# bootstrap order is binarize(defaults) -> compute_spec_stats.py -> make_configs.py ->
# train, and since spec_min/max are read only at training time no re-binarize is needed.
# variance produces no mel, so this is attached to acoustic only.
EXTRA_BASE = {'acoustic': '\n  - configs/pansori/spec_stats.yaml'}

KIND_HEADER = """# Pansori fine-tune — the shared {kind} layer (generated)
# Generated by python pansori/make_configs.py. Do not edit directly; fix the generator.
#
# This file **knows nothing about the corpus.** The experiment file layers it into
# base_config alongside a data_*.yaml and decides binary_data_dir — see configs/exp/.

base_config:
  - configs/{kind}.yaml{extra_base}

dictionaries:
  ko: dictionaries/korean-coda.txt
extra_phonemes: []

num_lang: 1
use_lang_id: false

binarization_args:
  num_workers: 4
use_spk_id: true

# Pansori's range. Male tongseong (chest voice) goes down to MIDI 35 = 61.7 Hz by the
# ROSVOT notes, so at the default of 65 Hz the low register is treated as unvoiced
# wholesale. The measured ceiling is 740 Hz.
f0_min: 55
f0_max: 750
pe: rmvpe
pe_ckpt: checkpoints/rmvpe/model.pt

# ---- fine-tune ------------------------------------------------------------
# Turn the two lines below on after downloading a public pre-trained checkpoint. The
# pre-trained models use a Chinese phoneme set, so the phoneme embedding is wholly
# mismatched and must go on the ignore list. The actual state_dict keys differ per
# checkpoint, so check them against the file after downloading it.
finetune_enabled: false
finetune_ckpt_path: null
finetune_ignored_params:
{ignored}
finetune_strict_shapes: false
"""

ACOUSTIC = """
# The first training run goes without augmentation. Pansori's range is already wide, and
# attaching key_shift/speed embeddings means those values have to be passed at inference
# too, which adds one more stage to the pipeline.
use_key_shift_embed: false
use_speed_embed: false
augmentation_args:
  random_pitch_shifting:
    enabled: false
  fixed_pitch_shifting:
    enabled: false
  random_time_stretching:
    enabled: false

# spec_min/spec_max come from the spec_stats.yaml in the base_config above.
# Rebuild the corpus and you must re-measure with compute_spec_stats.py and re-run this.

max_batch_frames: 50000
max_batch_size: 32
pl_trainer_precision: '16-mixed'
"""

VARIANCE = """
# upstream VarianceTask + per-phone-class duration metrics. The upstream files are left
# alone and only task_cls is swapped -- the reasoning and what gets added are in the
# header of pansori/variance_task.py. The existing rhythm_corr / ph_dur_acc still come
# out unchanged (keeping the comparison line with earlier runs).
task_cls: pansori.variance_task.PansoriVarianceTask

# How many utterances the new metrics cover. 0 = the whole validation set.
# upstream's rhythm_corr / ph_dur_acc are gated by num_valid_plots(10) and so score only
# the first 10. Duration inference is one conv and effectively free, so run it over all.
num_valid_metric_items: 0

predict_dur: true
predict_pitch: true
predict_energy: false
predict_breathiness: false
predict_voicing: false
predict_tension: false
use_glide_embed: false

max_batch_frames: 80000
max_batch_size: 32
pl_trainer_precision: '16-mixed'
"""

DATA_HEADER = """# Pansori corpus — {data} (generated)
# Generated by python pansori/make_configs.py --data {data} --name {name}.
#
# The speaker list has to match what 08_export.py actually wrote to disk, so it is not
# maintained by hand. This file holds **only what depends on the corpus** — the
# binary_data_dir, which differs per kind, is decided by the experiment file
# (configs/exp/).
"""

IGNORED = ['model.fs2.encoder.embed_tokens', 'model.fs2.txt_embed', 'model.fs2.spk_embed']

# openvpi always puts 'SP' (silence) and 'AP' (breath) in the phoneme set
# (utils/phoneme_utils.py:18), and binarize only passes if every member of the set
# actually appears in the corpus. So this block is decided by the corpus, not by a
# person -- leave AP in the set when the labels have none and binarize dies; merge them
# when the labels do have it and you smear away the breaths you just labelled. Which
# case you are in is knowable only from transcriptions.csv.
MERGED_SP_AP = """
# This corpus's labels carry no breath distinction (MFA alignment) -- 06_merge.py turns
# every note-uncovered silence into SP. So the two are merged onto one index. Leaving the
# labels to say what they say is more correct than inventing a distinction that is not
# there.
merged_phoneme_groups:
  - [SP, AP]
"""

SPLIT_SP_AP = """
# This corpus genuinely labelled breath (AP) (SOFA alignment), so it is not merged with
# SP -- merging would throw away the distinction that was just labelled. upstream's
# default is `merged_phoneme_groups: []` (configs/acoustic.yaml:8), so writing nothing
# is enough.
"""


def corpus_has_ap(data_root: Path) -> bool:
    """Does an AP token actually appear in this corpus's ph_seq?

    Asks exactly the condition binarize requires. datasets_block reads the same CSVs
    anyway, but that counts utterances while this looks at phonemes, so they run apart.
    """
    for path in sorted(p for p in data_root.iterdir() if p.is_dir()):
        csv_path = path / 'transcriptions.csv'
        if not csv_path.exists():
            continue
        with open(csv_path, encoding='utf-8') as f:
            for row in csv.DictReader(f):
                if 'AP' in row['ph_seq'].split():
                    return True
    return False


def datasets_block(data_root: Path, rel: str) -> tuple:
    speakers = []
    for path in sorted(p for p in data_root.iterdir() if p.is_dir() and (p / 'transcriptions.csv').exists()):
        with open(path / 'transcriptions.csv', encoding='utf-8') as f:
            names = [row['name'] for row in csv.DictReader(f)]
        held = sum(1 for n in names if n.startswith(HOLDOUT.get(path.name, '\0')))
        speakers.append((path.name, len(names), held))
    speakers.sort(key=lambda x: -x[1])          # spk_id 0 = the speaker with the most

    lines, dropped = ['', 'datasets:'], []
    for spk_id, (name, count, held) in enumerate(speakers):
        lines += [f'  - raw_data_dir: {rel}/{name}',
                  f'    speaker: {name}',
                  f'    spk_id: {spk_id}',
                  '    language: ko']
        # A holdout that swallows a speaker's entire dataset leaves that speaker
        # with no training items at all: the embedding never gets a gradient, yet
        # validation still runs through it. Better to train the speaker and give
        # up its holdout than to keep a hold-out we cannot learn from.
        if name in HOLDOUT and held < count:
            lines += ['    test_prefixes:', f"      - '{HOLDOUT[name]}'"]
        else:
            if name in HOLDOUT:
                dropped.append((name, count))
            lines += ['    test_prefixes: []']
        lines[-1] += f'      # {count:,} utterances'
    return '\n'.join(lines) + '\n', len(speakers), dropped


def main() -> None:
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument('--data', default='data/pansori')
    parser.add_argument('--name', default='pansori',
                        help='name of the corpus layer -> configs/pansori/data_{name}.yaml')
    args = parser.parse_args()

    repo = Path(__file__).resolve().parent.parent
    out_dir = repo / 'configs' / 'pansori'
    out_dir.mkdir(parents=True, exist_ok=True)

    data_root = repo / args.data
    has_ap = corpus_has_ap(data_root)
    merged = SPLIT_SP_AP if has_ap else MERGED_SP_AP

    ignored = '\n'.join(f'  - {p}' for p in IGNORED)
    for kind, tail in (('acoustic', ACOUSTIC), ('variance', VARIANCE)):
        out = out_dir / f'{kind}.yaml'
        out.write_text(
            KIND_HEADER.format(kind=kind, extra_base=EXTRA_BASE.get(kind, ''),
                               ignored=ignored) + tail,
            encoding='utf-8')
        print(f'{out.relative_to(repo)}')
    print('breath (AP) labelled -> no merged_phoneme_groups (SP/AP kept apart)' if has_ap
          else 'breath (AP) not labelled -> merged_phoneme_groups: [[SP, AP]]')

    block, n_spk, dropped = datasets_block(data_root, args.data)
    out = out_dir / f'data_{args.name}.yaml'
    out.write_text(
        DATA_HEADER.format(data=args.data, name=args.name) + block
        + f'\n# {n_spk} speakers (myeongchang + pooled unknown). num_spk must exceed the largest spk_id.\n'
        + f'num_spk: {n_spk + 1}\n' + merged,
        encoding='utf-8')
    print(f'{out.relative_to(repo)}  ({n_spk} speakers)')

    for name, count in dropped:
        print(f'⚠ {name}: the hold-out song is all {count:,} of this speaker\'s utterances '
              f'-> hold-out released (with zero training data the speaker embedding never learns)')
    missing = [s for s in HOLDOUT if not (data_root / s).exists()]
    if missing:
        print(f'⚠ speakers named in HOLDOUT are absent from the data: {missing}')


if __name__ == '__main__':
    main()
